// L-ENGINE-1 (WO-AEO-ENGINE-COUNT-CURRENCY-008 §6): fail the build when published copy states an
// engine count or engine list that is neither plan-attached nor in the reviewed allowlist.
//   npx tsx scripts/lint-engine-count.ts            # exit 1 on any unmarked line
//   npx tsx scripts/lint-engine-count.ts --ledger   # also writes docs/engine-count-sweep-2026-10-15.md
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { lintText, htmlText, sourceText, type AllowEntry, type LintHit } from '../src/lib/engineLint.js';

const allow: AllowEntry[] = JSON.parse(readFileSync('docs/engine-count-allowlist.json', 'utf8')).entries;
const walk = (d: string, ok: (f: string) => boolean): string[] => readdirSync(d).flatMap((n) => {
  const p = join(d, n); const st = statSync(p);
  return st.isDirectory() ? (['node_modules', '__tests__', 'images', 'img', 'og', 'fonts', 'expo'].includes(n) ? [] : walk(p, ok)) : ok(p) ? [p] : [];
});
const files = [
  ...walk('public', (f) => /\.(html|txt|xml)$/.test(f) && !/robots\.txt$|indexnow|[0-9a-f]{32}\.txt$/.test(f)),
  ...walk('src', (f) => /\.(tsx?|json)$/.test(f) && !/\.test\.|engines\.json|directories-catalog|engineLint\.ts/.test(f)),
];
const hits: LintHit[] = [];
for (const f of files) {
  const raw = readFileSync(f, 'utf8');
  const text = /\.(html|xml)$/.test(f) ? htmlText(raw) : /\.(tsx?)$/.test(f) ? sourceText(raw) : raw;
  hits.push(...lintText(f.replace(/\\/g, '/'), text, allow));
}
const bad = hits.filter((h) => !h.ok);
const unused = allow.filter((a) => !hits.some((h) => (a.file === '*' || h.file === a.file) && h.sentence.includes(a.text)));

if (process.argv.includes('--ledger')) {
  const by = (c: string) => hits.filter((h) => h.class === c).length;
  const rows = hits.map((h) => `| ${h.file}:${h.line} | ${h.sentence.replace(/\|/g, '/').slice(0, 260)} | ${h.class} | ${h.ok ? (h.class === 'CURRENT' ? 'plan-attached (fixed or already right)' : `keep — ${h.why}`) : `FAIL — ${h.why}`} |`);
  writeFileSync('docs/engine-count-sweep-2026-10-15.md', [
    '# Engine-count sweep — 2026-10-15 (WO-AEO-ENGINE-COUNT-CURRENCY-008)', '',
    'Generated by `npx tsx scripts/lint-engine-count.ts --ledger` over the published surface (public/ pages, llms.txt, llms-full.txt, feed, and the copy in src/). Pages built by a generator are fixed in the generator and rebuilt.', '',
    `Hits: ${hits.length} — CURRENT ${by('CURRENT')}, DATED ${by('DATED')}, ILLUSTRATIVE ${by('ILLUSTRATIVE')}, GENERAL ${by('GENERAL')}, SCORE ${by('SCORE')}, UNMARKED ${bad.length}.`, '',
    'Class: CURRENT = present-tense capability, must name its plan in the same sentence; DATED = a past measurement (kept, rule 1); ILLUSTRATIVE = a labeled sample (kept, rule 3); GENERAL = market description or manual instruction (kept, rule 4); SCORE = the AEO Score, checked against engines.json.', '',
    '| File:line | Text | Class | Action |', '|---|---|---|---|', ...rows, '',
    readFileSync('docs/engine-count-sweep-appendix.md', 'utf8'),
  ].join('\n'));
}
for (const h of bad) console.error(`L-ENGINE-1 ${h.file}:${h.line}: ${h.why}\n    "${h.sentence.slice(0, 200)}"`);
if (unused.length) console.error(`L-ENGINE-1: ${unused.length} allowlist entr${unused.length === 1 ? 'y matches' : 'ies match'} nothing (stale):\n` + unused.map((u) => `    ${u.file}: "${u.text}"`).join('\n'));
if (bad.length || unused.length) process.exit(1);
console.log(`L-ENGINE-1: ${hits.length} engine-count lines checked, all plan-attached or allowlisted.`);
